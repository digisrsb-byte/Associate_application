/**
 * Phase 8B.1 — Bundle server.ts (and local TS modules) to server.mjs for production.
 * npm packages stay external so runtime uses installed dependencies.
 * Requires esbuild (devDependency) — run during `npm run build`, not after omit=dev.
 */
import * as esbuild from 'esbuild';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = path.join(ROOT, 'server.ts');
const OUTFILE = path.join(ROOT, 'server.mjs');

if (!fs.existsSync(ENTRY)) {
  console.error(`[build:server] Missing entry: ${ENTRY}`);
  process.exit(1);
}

await esbuild.build({
  entryPoints: [ENTRY],
  outfile: OUTFILE,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  packages: 'external',
  sourcemap: true,
  logLevel: 'info',
  // Preserve import.meta.url so __dirname resolves next to server.mjs (project root).
  banner: {
    js: '// Generated by scripts/build-server.mjs — do not edit.\n',
  },
});

const stat = fs.statSync(OUTFILE);
console.info(
  `[build:server] Wrote ${path.relative(ROOT, OUTFILE)} (${stat.size} bytes)`
);
